"""
Calibration set for the vision model: cases labeled by Cristiano
(rotulos_andradas.json) → candidates generated by the SAME detector as the
app (worker/detect.py) in ±5 s windows → filmstrip + context.

Writes OUTPUT/calibration.json ([{id, hour, label, source, yolo, dist,
filmstrip, context}], image paths relative to OUTPUT) plus
OUTPUT/filmstrips/ and OUTPUT/contexts/ — the input of
web/scripts/calibrate.ts.

Usage: python evaluation/build_llm_calibration.py LABELS.json MINED_CANDIDATES.json VIDEO_DIR OUTPUT
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "worker"))
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "evaluation"))
import supervision as sv  # noqa: E402
from ultralytics import YOLO  # noqa: E402

import config  # noqa: E402
import detect as D  # noqa: E402
import legacy  # noqa: E402
from reader import VideoReader  # noqa: E402

# Cristiano's labels (Portuguese values of the labeling app) → categories
LABEL_MAP = {"bicicleta": "cyclists", "pedestre": "pedestrians", "carro": "cars",
             "moto": "motorcycles", "nada": "discarded"}
HALF = 75  # ±5 s at 15 fps
LINE_X = 960


def main():
    # external file in Portuguese: {"rotulos": {candidate id: "bicicleta" | ...}}
    labels = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))["rotulos"]
    mined = {c["id"]: c for c in legacy.load_candidates(Path(sys.argv[2]))}
    video_dir, output = Path(sys.argv[3]), Path(sys.argv[4])
    (output / "filmstrips").mkdir(parents=True, exist_ok=True)
    (output / "contexts").mkdir(parents=True, exist_ok=True)

    by_hour = defaultdict(list)
    for cid, l in labels.items():
        if l in LABEL_MAP:
            by_hour[mined[cid]["hour"]].append({**mined[cid], "label": LABEL_MAP[l]})

    model = YOLO(str(ROOT / config.MODEL))
    bike_model = YOLO(str(ROOT / config.BICYCLE_MODEL))
    classes = sorted({0, 1, 3, *config.CAR_CLASSES})
    result = []

    for hour in sorted(by_hour):
        cases = sorted(by_hour[hour], key=lambda c: c["frame"])
        # merged windows
        windows = []
        for c in cases:
            a, b = c["frame"] - HALF, c["frame"] + HALF
            if windows and a <= windows[-1][1]:
                windows[-1][1] = max(windows[-1][1], b)
            else:
                windows.append([a, b])
        reader = VideoReader(str(video_dir / f"Andradas_{hour}.mp4"))
        idx = -1
        target_frames = {c["frame"] for c in cases}
        for a, b in windows:
            while idx + 1 < a and reader.skip():
                idx += 1
            trackers = {g: sv.ByteTrack() for g in D.GROUPS}
            tracks, target_images = {}, {}
            while idx + 1 <= b:
                f = reader.read()
                if f is None:
                    break
                idx += 1
                if idx in target_frames:
                    target_images[idx] = f
                r = model(f, conf=config.CONFIDENCE, iou=config.IOU, imgsz=640, classes=classes,
                          agnostic_nms=True, verbose=False)[0]
                dets = sv.Detections.from_ultralytics(r)
                rb = bike_model(f, conf=config.CONFIDENCE, iou=config.IOU, imgsz=640, classes=[1],
                                verbose=False)[0]
                pc = lambda d, ids: d[np.isin(d.class_id, ids)] if len(d) else d  # noqa: E731
                tracked = {
                    "ped": trackers["ped"].update_with_detections(pc(dets, [0])),
                    "bike": trackers["bike"].update_with_detections(sv.Detections.from_ultralytics(rb)),
                    "car": trackers["car"].update_with_detections(pc(dets, config.CAR_CLASSES)),
                    "moto": trackers["moto"].update_with_detections(pc(dets, config.MOTORCYCLE_CLASSES)),
                }
                for g, d in tracked.items():
                    D._record(tracks, g, d, f, idx)
                D._associate(tracks, tracked["ped"], tracked["bike"], tracked["moto"], 1.0)
            tracks = D.splice_tracks(tracks, 15.0, 1.0)

            for c in cases:
                if not (a <= c["frame"] <= b):
                    continue
                target = np.array([LINE_X, c["y"]]) if c.get("y") is not None else None
                if c.get("box"):
                    x1, y1, x2, y2 = c["box"]
                    target = np.array([(x1 + x2) / 2, (y1 + y2) / 2])
                best, best_d = None, 1e9
                for tr in tracks.values():
                    if tr.n < D.MIN_OBS:
                        continue
                    fr = np.array(tr.frames)
                    k = int(np.argmin(np.abs(fr - c["frame"])))
                    if abs(fr[k] - c["frame"]) > 10:
                        continue
                    bx = tr.boxes[k]
                    center = np.array([(bx[0] + bx[2]) / 2, (bx[1] + bx[3]) / 2])
                    d = np.linalg.norm(center - target)
                    # the bike/motorcycle rider: an associated person loses to the vehicle
                    if tr.group == "ped" and tr.associated():
                        d += 40
                    if d < best_d:
                        best, best_d = tr, d
                if best is None or best_d > 200:
                    continue
                D.save_filmstrip(best, output / "filmstrips" / f"{c['id']}.jpg")
                image = target_images.get(c["frame"])
                if image is not None:
                    fr = np.array(best.frames)
                    bx = best.boxes[int(np.argmin(np.abs(fr - c["frame"])))]
                    x1, y1, x2, y2, ow, oh = D._clip_region(best, c["frame"] - 22, c["frame"] + 22,
                                                            1920, 1080, 1.0)
                    img = cv2.resize(image[y1:y2, x1:x2].copy(), (ow, oh), interpolation=cv2.INTER_AREA)
                    sx, sy = ow / (x2 - x1), oh / (y2 - y1)
                    cv2.line(img, (int((LINE_X - x1) * sx), 0), (int((LINE_X - x1) * sx), oh),
                             (0, 220, 255), 2)
                    cv2.rectangle(img, (int((bx[0] - x1) * sx), int((bx[1] - y1) * sy)),
                                  (int((bx[2] - x1) * sx), int((bx[3] - y1) * sy)), (0, 0, 255), 2)
                    cv2.imwrite(str(output / "contexts" / f"{c['id']}.jpg"), img,
                                [cv2.IMWRITE_JPEG_QUALITY, 85])
                group = best.associated() or best.group
                result.append({"id": c["id"], "hour": hour, "label": c["label"], "source": c["source"],
                               "yolo": D.GROUP_CATEGORY[group], "dist": round(float(best_d), 1),
                               "filmstrip": f"filmstrips/{c['id']}.jpg",
                               "context": f"contexts/{c['id']}.jpg"})
        reader.close()
        print(hour, "cases", len(cases), "matched so far", len(result), flush=True)

    (output / "calibration.json").write_text(json.dumps(result, ensure_ascii=False, indent=1),
                                             encoding="utf-8")
    print("total matched:", len(result))


if __name__ == "__main__":
    main()
